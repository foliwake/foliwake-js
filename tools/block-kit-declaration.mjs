// The standalone declaration of @foliwake/block-kit (dist/foliwake.d.ts), composed by tools/build.mjs from what tsc
// generated: the kit's declarations (block-kit.d.ts, from src/block-kit.ts) with the lit-html declarations they
// re-export (src/lit-html.d.ts: `TemplateResult`, `html`, `nothing`) inlined in place of their import, so the file
// imports nothing. create-foliwake and the Foliwake CLI write it into site folders, which have no node_modules.
// Only TypeScript's parser is used (already the build's compiler): no declaration bundler.
import ts from 'typescript';

const LIT_HTML = './lit-html.js';

const HEADER = `// Types of the module \`@foliwake/block-kit\` (block-kit.js; \`foliwake\` is its previous specifier),
// self-contained for editors of a site folder without node_modules: create-foliwake and the Foliwake CLI write it as
// \`.foliwake/types/foliwake.d.ts\` (jsconfig \`paths\` maps both specifiers there), and
// \`.foliwake/types/blocks/<name>.d.ts\`, generated from each block's JSON, adds the block to \`FoliwakeBlocks\`.
// The package's own entry (index.d.ts) re-exports these and the blocks contract's types.
// Generated by the package's build from src/block-kit.ts and src/lit-html.d.ts: edit those, not this file.
`;

const parse = (name, text) => ts.createSourceFile(name, text, ts.ScriptTarget.Latest, true);

/** A statement's source text with its TSDoc, without other leading comments (a file header). */
const textOf = (statement, file) => file.text.slice(statement.getStart(file, true), statement.end);

const fromLitHtml = (statement) => statement.moduleSpecifier?.text === LIT_HTML;

/** The local names an `import { … } from './lit-html.js'` binds. */
function importedNames(statement) {
  return statement.importClause.namedBindings.elements.map((element) => element.name.text);
}

/** `export { html, nothing }` or `export type { TemplateResult }`: names re-exported as they were imported. */
function reexportedNames(statement, imported) {
  if (!ts.isExportDeclaration(statement) || statement.moduleSpecifier || !statement.exportClause) return null;
  const names = statement.exportClause.elements.map((element) => element.name.text);
  return names.every((name) => imported.has(name)) ? names : null;
}

/** The name a top-level declaration of lit-html.d.ts declares (a function, a const, an interface). */
function declaredName(statement) {
  if (ts.isVariableStatement(statement)) return statement.declarationList.declarations[0].name.text;
  return statement.name?.text;
}

/** The kit's declarations split: what it re-exports from lit-html, and its own statements as text. */
function splitKit(kit) {
  const imported = new Set();
  const reexported = [];
  const own = [];
  for (const statement of kit.statements) {
    if (ts.isImportDeclaration(statement) && fromLitHtml(statement)) {
      for (const name of importedNames(statement)) imported.add(name);
      continue;
    }
    const names = reexportedNames(statement, imported);
    if (names) reexported.push(...names);
    else own.push(textOf(statement, kit));
  }
  const dangling = [...imported].filter((name) => !reexported.includes(name));
  if (dangling.length) throw new Error(`block-kit.d.ts uses lit-html's ${dangling.join(', ')} without re-exporting`);
  return { reexported, own };
}

/** The declarations of lit-html.d.ts for `names`, in that file's order. */
function litHtmlDeclarations(lit, names) {
  const found = lit.statements.filter((statement) => names.includes(declaredName(statement)));
  const missing = names.filter((name) => !found.some((statement) => declaredName(statement) === name));
  if (missing.length) throw new Error(`lit-html.d.ts does not declare ${missing.join(', ')}`);
  return found.map((statement) => textOf(statement, lit));
}

/** The standalone foliwake.d.ts from the texts of the generated block-kit.d.ts and of src/lit-html.d.ts. */
export function standaloneDeclaration(kitText, litText) {
  const { reexported, own } = splitKit(parse('block-kit.d.ts', kitText));
  const inlined = litHtmlDeclarations(parse('lit-html.d.ts', litText), reexported);
  // `export {}`: only what is declared with `export` is exported (a .d.ts without it exports every declaration).
  return `${HEADER}${[...inlined, ...own, 'export {};'].join('\n')}\n`;
}
