#!/usr/bin/env node
// `pnpm core-contract:sync <engine checkout>`: copies the contract the engine generates from its core router
// (`core-contract/` of the engine, written by its `pnpm core:contract`) into packages/core-contract/engine/,
// records their SHA-256 in engine/checksums.json, and writes the package's sources from them:
//
//   src/procedures.d.ts  the engine's index.d.ts as it is (every procedure's input and output types)
//   src/manifest.ts      manifest.json as a module (API version, digest, each procedure's kind)
//   src/errors.ts        errors.json as a module (error categories, known codes)
//
// Updating the contract is one step: run this against the engine version the CLI should speak, commit the result.
// test/core-contract.test.js fails when engine/ differs from its checksums or src/ from what engine/ gives.
import { createHash } from 'node:crypto';
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const PACKAGE_DIR = path.join(ROOT, 'packages/core-contract');
export const ENGINE_DIR = path.join(PACKAGE_DIR, 'engine');
export const CONTRACT_FILES = Object.freeze(['manifest.json', 'errors.json', 'index.d.ts']);

const HEADER = '// Generated by tools/core-contract-sync.mjs from engine/';

export const sha256 = (text) => createHash('sha256').update(text).digest('hex');
const read = (file) => readFileSync(file, 'utf8');

/** The checksums of the copied engine files, as engine/checksums.json holds them. */
export function checksumsOf(dir = ENGINE_DIR) {
  return Object.fromEntries(CONTRACT_FILES.map((name) => [name, sha256(read(path.join(dir, name)))]));
}

function manifestModule(manifest) {
  const kinds = Object.entries(manifest.procedures).map(([name, kind]) => `  ${JSON.stringify(name)}: '${kind}',`);
  return [
    `${HEADER}manifest.json. Do not edit.`,
    '',
    '/** The version of the core API this contract describes. */',
    `export const CORE_API = ${manifest.api};`,
    '',
    '/** The digest of the contract; `GET /api/version` of a server with the same contract answers it too. */',
    `export const CONTRACT_DIGEST = ${JSON.stringify(manifest.digest)};`,
    '',
    '/** Every procedure of core over HTTP and its kind. */',
    `export const PROCEDURES: Readonly<Record<string, 'query' | 'mutation'>> = Object.freeze({`,
    ...kinds,
    '});',
    '',
  ].join('\n');
}

function errorsModule(errors) {
  const categories = errors.categories.map((category) => `  '${category}',`);
  const codes = Object.entries(errors.codes).map(([code, category]) => `  ${code}: '${category}',`);
  return [
    `${HEADER}errors.json. Do not edit.`,
    '',
    '/** Every category of a core error, in order. */',
    'export const ERROR_CATEGORIES = Object.freeze([',
    ...categories,
    '] as const);',
    '',
    '/**',
    ' * The error codes the engine raises, with their category (`a | b` when it raises one with several).',
    ' * Not closed: a client handles a code it does not know by its category.',
    ' */',
    'export const ERROR_CODES: Readonly<Record<string, string>> = Object.freeze({',
    ...codes,
    '});',
    '',
  ].join('\n');
}

/** The package sources engine/ gives, by path relative to the package. */
export function generatedSources(dir = ENGINE_DIR) {
  return {
    'src/procedures.d.ts': read(path.join(dir, 'index.d.ts')),
    'src/manifest.ts': manifestModule(JSON.parse(read(path.join(dir, 'manifest.json')))),
    'src/errors.ts': errorsModule(JSON.parse(read(path.join(dir, 'errors.json')))),
  };
}

function sync(engineCheckout) {
  const from = path.join(path.resolve(engineCheckout), 'core-contract');
  for (const name of CONTRACT_FILES) copyFileSync(path.join(from, name), path.join(ENGINE_DIR, name));
  writeFileSync(path.join(ENGINE_DIR, 'checksums.json'), `${JSON.stringify(checksumsOf(), null, 2)}\n`);
  for (const [file, text] of Object.entries(generatedSources())) writeFileSync(path.join(PACKAGE_DIR, file), text);
  console.log(`packages/core-contract: engine/ and src/ from ${from}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (!process.argv[2]) {
    console.error('usage: node tools/core-contract-sync.mjs <engine checkout>');
    process.exit(2);
  }
  sync(process.argv[2]);
}
